function startGame()
 sync(3,1,false)
 newGame()
 dbLoad()
 local opp=OPPONENTS[OPP_SEL]
 G.oppName=opp.name
 G.strategy=opp.strategy or STRATEGY_DEFAULT
 local plrDeck=#DB.deck>0 and DB.deck or DECK1
 for i,id in ipairs(plrDeck) do G.deck[1][i]=id end
 for i,id in ipairs(opp.deck) do G.deck[2][i]=id end
 shuffle(G.deck[1]); shuffle(G.deck[2])
 -- Extra Decks (player = DB.extra if user has built one, else DECK1_EXTRA;
 -- opponent = opp.extra or empty). Stored as full card instances (not IDs),
 -- since the ED isn't shuffled and is owner-visible.
 local plrExtra=(#DB.extra>0 and DB.extra) or DECK1_EXTRA or {}
 for _,id in ipairs(plrExtra) do G.extra[1][#G.extra[1]+1]=makeCard(id) end
 for _,id in ipairs(opp.extra or {}) do G.extra[2][#G.extra[2]+1]=makeCard(id) end
 for _=1,4 do drawCard(1,true); drawCard(2,true) end
 startRPS()
 SCENE="rps"
end

function BOOT()
 G={tick=0}
 SCENE="title"
 TITLE_SEL=1
 music(1,-1,-1,true,true)
end

function TIC()
 G.tick=G.tick+1
 bumpStats()  -- per-frame baseline so stat caches never live more than 1 frame
 if SCENE=="title" then
  handleTitleInput()
  drawTitle()
  return
 end
 if SCENE=="menu" then
  handleMenuInput()
  drawMenu()
  return
 end
 if SCENE=="oppselect" then
  handleOppSelectInput()
  drawOppSelect()
  return
 end
 if SCENE=="oppconfirm" then
  handleOppConfirmInput()
  if SCENE=="oppconfirm" then tickOppConfirm() end
  if SCENE=="oppconfirm" then drawOppConfirm() end
  return
 end
 if SCENE=="deckbuild" then
  handleDeckBuildInput()
  drawDeckBuild()
  return
 end
 if SCENE=="rps" then
  tickRPS()
  handleRPSInput()
  drawRPS()
  return
 end
 if SCENE=="trans" then
  drawTrans()
  return
 end
 -- Debug: B benchmarks the move simulator, traces to the console. The game
 -- reads only btnp elsewhere, so this can't collide with normal input.
 if keyp(2) then simBench() end
 handleInput()
 if SCENE~="game" then return end
 autoPhase()
 aiTick()
 tickAnims()
 procTick()
 tickDispLp()
 cls(CB)
 rect(FA_X,0,FA_W,SH,CMAT)
 -- Playmat dither: sparse darker dots for subtle texture
 for y=0,SH-1,4 do
  for x=FA_X,SW-1,4 do
   pix(x,y,CB)
  end
 end
 -- Ornamental field border (gold)
 rectb(FA_X,0,FA_W,SH,9)
 drawOppSide()
 line(COL[0],DIV_Y,COL[4]+ZW_SPEC-1,DIV_Y,CD)
 drawPlrSide()
 drawCursor()
 drawAnims()
 drawPanel()
 drawChain()
 drawModeBanner()
 if G.mode=="gy_view" and G.gyView then drawGYView() end
 if G.mode=="ed_view" and G.edView then drawEDView() end
 if G.mode=="sel_deck" and G.deckSel then drawDeckSelect() end
 if G.infoCard then drawDBInfo(G.infoCard) end
 drawPopup()
 if G.winner then drawGameOver() end
end

